"""**1. Utility Functions**"""

def to_float(X):
    X = np.asarray(X, dtype=np.float64)
    return np.nan_to_num(X)

def fro_norm(X):
    return np.sqrt(np.sum(X**2))

def snr_db(true, est):
    true, est = to_float(true), to_float(est)
    err = fro_norm(true - est)
    if err == 0:
        err = 1e-12
    return 20 * np.log10(fro_norm(true) / err)

def hard_threshold(X, tau):
    return np.where(np.abs(X) > tau, X, 0)

def truncated_svd(X, k):
    U, S, Vt = np.linalg.svd(X, full_matrices=False)
    k = min(k, len(S))
    return U[:, :k], S[:k], Vt[:k, :]

def singular_value_thresholding(X, tau):
    U, S, Vt = svd(X, full_matrices=False)
    S2 = np.maximum(S - tau, 0)
    return U @ np.diag(S2) @ Vt

def soft_thresholding(X, tau):
    return np.sign(X) * np.maximum(np.abs(X) - tau, 0)

"""## 1.1 Background

Background subtraction aims to identify moving objects (foreground)
in a video by separating them from the static background. This is
commonly formulated as:

**Video = Background (Low-Rank) + Foreground (Sparse or Dynamic)**

Matrix and tensor decomposition techniques are ideal for this because:
- Background across frames is highly correlated → low rank
- Moving objects appear only in some frames → sparse

## 1.2 Problem Definition

Given a video represented as:
- A **matrix** (vectorized frames) or
- A **tensor** (height × width × time)

Find:
- **L** → low-rank background
- **S** → sparse or dynamic foreground

We evaluate the performance of 6 decomposition methods in reconstructing L and S.

**2. MATRIX METHODS**

2.1 RPCA
"""

def rpca(D, lam=None, mu=None, tol=1e-7, max_iter=300):
    D = to_float(D)
    m, n = D.shape

    if lam is None:
        lam = 1 / np.sqrt(max(m, n))
    if mu is None:
        mu = (m * n) / (4 * np.sum(np.abs(D)) + 1e-8)

    L = np.zeros_like(D)
    S = np.zeros_like(D)
    Y = np.zeros_like(D)

    for _ in range(max_iter):
        L = singular_value_thresholding(D - S + Y / mu, 1 / mu)
        S = soft_thresholding(D - L + Y / mu, lam / mu)
        R = D - L - S
        Y += mu * R

        if fro_norm(R) / fro_norm(D) < tol:
            break

    return L, S

"""2.2 CUR Decomposition"""

def cur_decomposition(D, k=10):
    m, n = D.shape

    col_energy = np.sum(D**2, axis=0)
    row_energy = np.sum(D**2, axis=1)

    col_idx = np.argsort(col_energy)[-k:]
    row_idx = np.argsort(row_energy)[-k:]

    C = D[:, col_idx]
    R = D[row_idx, :]
    U = D[np.ix_(row_idx, col_idx)]

    U_pinv = np.linalg.pinv(U)
    L = C @ U_pinv @ R

    return L

"""2.3 IRCUR (Iterated Robust CUR)"""

def ircur(D, r=10, z0=3, gamma=0.95, max_iter=8):

    Dn = D / (np.max(np.abs(D)) + 1e-8)
    L = np.zeros_like(Dn)
    S = np.zeros_like(Dn)
    z = z0

    for _ in range(max_iter):
        S = hard_threshold(Dn - L, z)
        z *= gamma

        R = Dn - S
        row_e = np.sum(R**2, axis=1)
        col_e = np.sum(R**2, axis=0)

        rows = np.argsort(row_e)[-r:]
        cols = np.argsort(col_e)[-r:]

        C = R[:, cols]
        R_sub = R[rows, :]
        U = R[np.ix_(rows, cols)]

        Uu, Ss, Vv = truncated_svd(U, r)
        U_pinv = Vv.T @ np.diag(1 / (Ss + 1e-12)) @ Uu.T

        L = C @ U_pinv @ R_sub

    L *= np.max(np.abs(D))
    S *= np.max(np.abs(D))
    return L, S

"""**3. TENSOR METHODS**

3.1 CP Decomposition

"""

def cp_reconstruct(X, rank=5):
    fac = parafac(X, rank=rank)
    return tl.cp_to_tensor(fac)

"""3.2 Tucker Decomposition"""

def tucker_reconstruct(X, ranks=(10,10,3)):
    core, factors = tucker(X, rank=ranks)
    return tl.tucker_to_tensor((core, factors))

"""3.3 RTCUR (True Fiber CUR Tensor Decomposition)"""

def rtcur_reconstruct(X, ranks=(10,10,3)):
    X = to_float(X)
    norm = fro_norm(X)
    Xn = X / (norm + 1e-12)
    factors = []

    for mode, r in enumerate(ranks):
        X_un = tl.unfold(Xn, mode)
        e_rows = np.sum(X_un**2, axis=1)
        e_cols = np.sum(X_un**2, axis=0)

        row_idx = np.argsort(e_rows)[-r:]
        col_idx = np.argsort(e_cols)[-r:]

        C = X_un[:, col_idx]
        R = X_un[row_idx, :]
        U = X_un[np.ix_(row_idx, col_idx)]

        U_pinv = np.linalg.pinv(U)
        factor = C @ U_pinv
        factors.append(factor)

    core = Xn
    for mode, F in enumerate(factors):
        core = tl.tenalg.mode_dot(core, np.linalg.pinv(F), mode=mode)

    L = core
    for mode, F in enumerate(factors):
        L = tl.tenalg.mode_dot(L, F, mode=mode)

    return L * norm, None

